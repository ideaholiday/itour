## Ram Mandir darshan: what to know before you go

The temple is built in the Nagara style from pink sandstone, with carved pillars and a sanctum that holds the idol of Ram Lalla. A few practical points make the visit much easier:

- **Carry as little as possible.** Mobile phones, cameras, bags, electronic items and leather goods are not allowed inside. Use the cloakroom and locker facilities near the entry.
